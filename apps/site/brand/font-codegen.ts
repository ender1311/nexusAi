import { WEB_FONTS, type FontKey } from "./font-stacks";
import type { BrandPreset } from "./types";

const HEADER = "// GENERATED by apps/site/scripts/gen-active-fonts.ts. Do not edit; see brand/README.md.";

const camel = (key: string) => key.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase());

function moduleSource(keys: FontKey[], preload: boolean, exportName: string, note: string): string {
  const fonts = keys.flatMap((key) => {
    const font = WEB_FONTS[key];
    return font ? [{ key, ...font }] : [];
  });
  if (fonts.length === 0) return `${HEADER}\n// ${note}\n// No web fonts: every font here is a system stack.\n\nexport const ${exportName} = "";\n`;
  const loaders = [...new Set(fonts.map((f) => f.loader))].sort();
  const lines = fonts.map((f) =>
    `const ${camel(f.key)} = ${f.loader}({ subsets: ["latin"], ${f.options}variable: "${f.variable}", display: "swap", preload: ${preload} });`);
  return [
    HEADER,
    `// ${note}`,
    `import { ${loaders.join(", ")} } from "next/font/google";`,
    "",
    ...lines,
    "",
    `export const ${exportName} = [${fonts.map((f) => `${camel(f.key)}.variable`).join(", ")}].join(" ");`,
    "",
  ].join("\n");
}

/** The web fonts a preset uses (display, body, mono), without duplicates or system stacks. */
export function presetWebFonts(preset: BrandPreset): FontKey[] {
  return [...new Set([preset.fonts.display, preset.fonts.body, preset.fonts.mono])].filter((k) => WEB_FONTS[k] !== undefined);
}

/**
 * The two generated font modules for the active preset:
 * - active: its own fonts, preloaded (the root layout puts these on <html>);
 * - preview: every other web font, not preloaded (only /nexus/brand uses them).
 */
export function generateFontModules(active: BrandPreset): { active: string; preview: string } {
  const activeKeys = presetWebFonts(active);
  const otherKeys = (Object.keys(WEB_FONTS) as FontKey[]).filter((k) => !activeKeys.includes(k));
  return {
    active: moduleSource(activeKeys, true, "activeFontVariables", `Fonts for NEXT_PUBLIC_BRAND=${active.id}, preloaded.`),
    preview: moduleSource(otherKeys, false, "previewFontVariables", `Every other web font, for /nexus/brand only (active brand: ${active.id}).`),
  };
}
